export function normalizeLinearAlgebraEditorLatex(latex: string): string {
  return latex
    .trim()
    .replace(/\s+/g, '')
    .replace(/\\left/g, '')
    .replace(/\\right/g, '')
    .replace(/\\,/g, '')
    .replace(/\\;/g, '')
    .replace(/\\operatorname\{rank\}/gi, 'rank')
    .replace(/\\operatorname\{rref\}/gi, 'rref')
    .replace(/\\operatorname\{null\}/gi, 'null')
    .replace(/\\operatorname\{col\}/gi, 'col')
    .replace(/\\operatorname\{basis\}/gi, 'basis')
    .replace(/\\operatorname\{coords?\}/gi, 'coords')
    .replace(/\\operatorname\{change\}/gi, 'change')
    .replace(/\\operatorname\{changebasis\}/gi, 'changebasis')
    .replace(/\\operatorname\{lu\}/gi, 'lu')
    .replace(/\\operatorname\{plu\}/gi, 'plu')
    .replace(/\\operatorname\{qr\}/gi, 'qr')
    .replace(/\\operatorname\{(?:projcol|colproj)\}/gi, 'projcol')
    .replace(/\\operatorname\{(?:ls|least|lstsq)\}/gi, 'ls')
    .replace(/\\operatorname\{mpow\}/gi, 'mpow')
    .replace(/\\operatorname\{lusolve\}/gi, 'lusolve')
    .replace(/\\operatorname\{plusolve\}/gi, 'plusolve')
    .replace(/\\operatorname\{invertible\}/gi, 'invertible')
    .replace(/\\operatorname\{charpoly\}/gi, 'charpoly')
    .replace(/\\operatorname\{eigen\}/gi, 'eigen')
    .replace(/\\operatorname\{(?:diag|diagonalize)\}/gi, 'diag')
    .replace(/\\operatorname\{proj\}_\{u\}/g, 'proj_u')
    .replace(/\\operatorname\{proj\}_u/g, 'proj_u')
    .replace(/\\operatorname\{proj\}_\{v\}/g, 'proj_v')
    .replace(/\\operatorname\{proj\}_v/g, 'proj_v')
    .replace(/\\operatorname\{proj\}/g, 'proj')
    .replace(/\\operatorname\{cross\}/gi, 'cross')
    .replace(/\\operatorname\{(?:triple|scalartriple|stp)\}/gi, 'triple')
    .replace(/\\operatorname\{orth\}_\{u\}/g, 'orth_u')
    .replace(/\\operatorname\{orth\}_u/g, 'orth_u')
    .replace(/\\operatorname\{orth\}_\{v\}/g, 'orth_v')
    .replace(/\\operatorname\{orth\}_v/g, 'orth_v')
    .replace(/\\operatorname\{unit\}/g, 'unit')
    .replace(/\\operatorname\{orthogonal\}/g, 'orthogonal')
    .replace(/\\operatorname\{gram\}/g, 'gram')
    .replace(/\\operatorname\{span\}/g, 'span')
    .replace(/\\operatorname\{independent\}/g, 'independent')
    .replace(/\\operatorname\{profile\}/g, 'profile')
    .replace(/\\operatorname\{definite\}/gi, 'definite')
    .replace(/\\operatorname\{svd\}/gi, 'svd')
    .replace(/\\operatorname\{pinv\}/gi, 'pinv')
    .replace(/\\operatorname\{cond\}/gi, 'cond')
    .replace(/\\operatorname\{nrank\}/gi, 'nrank')
    .replace(/\\operatorname\{transpose\}/gi, 'transpose')
    .replace(/\\operatorname\{adjoint\}/gi, 'adjoint')
    .replace(/\\operatorname\{angle\}/g, 'angle')
    .replace(/\\operatorname\{dot\}/gi, 'dot')
    .replace(/\\operatorname\{norm\}/gi, 'norm')
    .replace(/\\operatorname\{gramschmidt\}/gi, 'gram')
    .replace(/\\operatorname\{(parallel|distance|parallelogramArea|triangleArea|volume)\}/g, '$1')
    .replace(/\\det/g, 'det')
    .replace(/\\angle/g, 'angle')
    .replace(/\\dfrac/g, '\\frac')
    .replace(/\\tfrac/g, '\\frac')
    .replace(/\\lbrack/g, '[')
    .replace(/\\rbrack/g, ']');
}
